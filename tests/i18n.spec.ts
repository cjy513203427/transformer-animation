/** Visible text, accessible names and the title that still contain Chinese (the 中文 link aside). */
async function chineseLeftovers(page: Page) {
  return page.evaluate(() => {
    const CJK = /[　-〿一-鿿＀-￯]/;
    const exempt = (el: Element | null) => !el || !!el.closest('[lang="zh-CN"], script, style');
    const found: string[] = [];
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      const text = node.textContent ?? '';
      if (CJK.test(text) && !exempt(node.parentElement)) found.push(text.trim().slice(0, 80));
    }
    // Text generated by CSS (::before / ::after content) is not in the DOM but still shows.
    for (const el of document.body.querySelectorAll('*')) {
      if (exempt(el)) continue;
      for (const pseudo of ['::before', '::after']) {
        const content = getComputedStyle(el, pseudo).content;
        if (content && content !== 'none' && CJK.test(content)) found.push(`${pseudo} ${content}`);
      }
    }
    for (const el of document.querySelectorAll('[aria-label], [title], [alt], [placeholder]')) {
      if (exempt(el)) continue;
      for (const name of ['aria-label', 'title', 'alt', 'placeholder']) {
        const value = el.getAttribute(name);
        if (value && CJK.test(value)) found.push(`${name}=${value.slice(0, 80)}`);
      }
    }
    if (CJK.test(document.title)) found.push(`document.title=${document.title}`);
    return found;
  });
}

const overflow = (page: Page) =>
  page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);

/**
 * Text that spills out of its box: SVG text wider than the rect drawn in the same group or
 * leaving the drawing, and HTML text wider than an element that is not meant to scroll.
 * Translations are longer than the Chinese source, so fixed boxes are the usual victims.
 */
async function spilledText(page: Page) {
  return page.evaluate(() => {
    const found: string[] = [];
    const name = (el: Element) => (el.textContent ?? '').trim().slice(0, 60);
    for (const text of document.querySelectorAll<SVGTextElement>('svg text')) {
      if (!text.getClientRects().length || !name(text)) continue;
      const t = text.getBoundingClientRect();
      for (const rect of [...(text.parentElement?.children ?? [])].filter(
        (el) => el.tagName === 'rect',
      )) {
        const r = rect.getBoundingClientRect();
        const cx = (t.left + t.right) / 2;
        const cy = (t.top + t.bottom) / 2;
        const inside = cx > r.left && cx < r.right && cy > r.top && cy < r.bottom;
        if (inside && (t.left < r.left - 1 || t.right > r.right + 1))
          found.push(`“${name(text)}” is wider than its box`);
      }
      const s = text.ownerSVGElement!.getBoundingClientRect();
      if (t.left < s.left - 1 || t.right > s.right + 1)
        found.push(`“${name(text)}” leaves the drawing`);
    }
    for (const el of document.querySelectorAll('body *')) {
      // KaTeX glyphs overhang their box by design; formulas are not translated text.
      if (el.closest('svg') || el.querySelector('.katex') || !el.getClientRects().length) continue;
      if (['auto', 'scroll'].includes(getComputedStyle(el).overflowX)) continue;
      const ownText = [...el.childNodes].some((n) => n.nodeType === 3 && n.textContent?.trim());
      if (ownText && el.clientWidth > 0 && el.scrollWidth > el.clientWidth + 1)
        found.push(`“${name(el)}” is wider than its <${el.tagName.toLowerCase()}>`);
    }
    return found;
  });
}

/** Checks the page, then clicks forward through every visible stepper; returns the clicks made. */
async function walkSteps(page: Page, locale: 'en' | 'de', label: string) {
  let clicks = 0;
  for (; clicks < 40; clicks++) {
    expect(await chineseLeftovers(page), `${label} after ${clicks} clicks`).toEqual([]);
    expect(await overflow(page), `${label} horizontal overflow`).toBeLessThanOrEqual(1);
    expect(await spilledText(page), `${label} text outside its box`).toEqual([]);
    let clicked = false;
    for (const button of await page.getByRole('button', { name: NEXT[locale] }).all()) {
      if ((await button.isVisible()) && (await button.isEnabled())) {
        await button.click();
        clicked = true;
        break;
      }
    }
    if (!clicked) break;
  }
  return clicks;
}

for (const locale of ['en', 'de'] as const)
  test.describe(`${locale} pages`, () => {
    for (const route of ROUTES)
      test(`${route}: every step is fully translated and fits the screen`, async ({ page }) => {
        const problems: string[] = [];
        page.on('pageerror', (error) => problems.push(`pageerror: ${error.message}`));
        page.on('console', (message) => {
          if (message.text().includes('[i18n] missing')) problems.push(message.text());
        });
        await page.goto(`/${locale}${route}`);
        await expect(page.locator('h1').first()).toBeVisible();
        await expect(page.locator('html')).toHaveAttribute('lang', locale);

        let clicks = 0;
        if (route === '/attention') {
          const names = ATTENTION[locale];
          expect(await chineseLeftovers(page), 'attention start').toEqual([]);
          await page.getByRole('button', { name: names.guided, exact: true }).click();
          expect(await chineseLeftovers(page), 'guided walkthrough').toEqual([]);
          await page.getByRole('button', { name: names.observe, exact: true }).click();
          expect(await chineseLeftovers(page), 'guided walkthrough, word chosen').toEqual([]);
          await page.getByRole('button', { name: names.leave, exact: true }).click();
          for (const level of names.levels) {
            await page.getByRole('button', { name: level, exact: true }).first().click();
            clicks += await walkSteps(page, locale, `${route} · ${level}`);
          }
        } else {
          clicks = await walkSteps(page, locale, route);
        }
        // Every experiment has at least six steps, so a translated stepper must have been found.
        expect(clicks, `${route} steps walked`).toBeGreaterThanOrEqual(5);
        expect(problems).toEqual([]);
      });
  });

test('the language switch keeps the experiment and its state', async ({ page }) => {
  await page.goto('/en/moe#lab=probe');
  await expect(page.locator('html')).toHaveAttribute('lang', 'en');
  const languages = page.getByRole('navigation', { name: 'Interface language' });
  await languages.getByRole('link', { name: 'Deutsch' }).click();
  await expect(page).toHaveURL(/\/de\/moe#lab=probe$/);
  await expect(page.locator('html')).toHaveAttribute('lang', 'de');
  await page
    .getByRole('navigation', { name: 'Sprache der Oberfläche' })
    .getByRole('link', { name: '中文' })
    .click();
  await expect(page).toHaveURL(/\/moe#lab=probe$/);
  await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN');
});

